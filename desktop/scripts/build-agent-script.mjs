// Build the page script injected by the Rust side from its TypeScript modules.
// The generated bundle is committed; the drift test runs this same script.
import { spawnSync } from "node:child_process";
import { writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const source = "src/browser-agent/index.ts";
const output = "src-tauri/src/browser_agent.js";
const banner = "// Generated by `bun run build:agent-script`; edit src/browser-agent instead.\n";

// Pin the bundler so the output does not depend on the installed bun.
const BUNDLER = "bun@1.3.14";

export function buildAgentScript() {
  const result = spawnSync(
    process.env.BUNX ?? "bunx",
    [BUNDLER, "build", source, "--format=iife", "--target=browser"],
    { cwd: root, encoding: "utf8", maxBuffer: 64 * 1024 * 1024 },
  );
  if (result.status !== 0) {
    throw new Error(result.stderr || `bunx ${BUNDLER} build exited with ${result.status}`);
  }
  return banner + result.stdout;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const text = buildAgentScript();
  if (process.argv.includes("--stdout")) process.stdout.write(text);
  else writeFileSync(path.join(root, output), text);
}
